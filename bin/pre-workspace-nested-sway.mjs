#!/usr/bin/env node

/** Launch an isolated nested Sway and its controller from the host terminal. */

import { mkdtempSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const controller = join(packageRoot, "bin", "pre-workspace.mjs");
const rawArgs = process.argv.slice(2);

function shellQuote(value) {
	return `'${value.replaceAll("'", "'\\\"'\\\"'")}'`;
}

function usage() {
	console.error(`Usage: pre-workspace-nested-sway [pre-workspace options]

Starts a Wayland-nested Sway window and launches pre-workspace inside it.
All options are passed to pre-workspace, for example:
  pre-workspace-nested-sway --allow-root "$HOME" --editor geany

The nested session has Super+Enter for foot and Super+Shift+E to exit.
Run this from the ordinary host terminal; do not copy setup commands into the
nested Sway window.`);
}

if (rawArgs.includes("--help")) { usage(); process.exit(0); }
const configDir = mkdtempSync(join(tmpdir(), "pre-nested-sway-"));
const command = [process.execPath, controller, ...rawArgs].map(shellQuote).join(" ");
const config = `# Generated by pre-workspace-nested-sway; do not edit.
set $mod Mod4
font pango:monospace 10
bindsym $mod+Return exec foot
bindsym $mod+Shift+e exec swaymsg exit
bindsym $mod+Shift+c reload
exec ${command}
`;
const configPath = join(configDir, "config");
writeFileSync(configPath, config, { mode: 0o600 });

const result = spawnSync("sway", ["--unsupported-gpu", "-c", configPath], {
	stdio: "inherit",
	env: { ...process.env, WLR_BACKENDS: "wayland", WLR_WL_OUTPUTS: "1" },
});
if (result.error) {
	console.error(`pre-workspace-nested-sway: could not start sway: ${result.error.message}`);
	process.exit(1);
}
process.exit(result.status ?? 1);
