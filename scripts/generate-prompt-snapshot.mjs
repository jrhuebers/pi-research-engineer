#!/usr/bin/env node
/** Generate the deterministic, provider-independent Pre prompt baseline. */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import {
	createAgentSession,
	DefaultResourceLoader,
	SessionManager,
	SettingsManager,
} from "@earendil-works/pi-coding-agent";
import { withResearchEngineeringGuidance } from "../extensions/research-engineering.ts";
import { applyToolPolicyToNames } from "../extensions/tool-policy.ts";

const repositoryRoot = resolve(new URL("..", import.meta.url).pathname);
const agentDir = resolve(repositoryRoot, ".pi", "agent");
const outputPath = resolve(repositoryRoot, "PRE_SYSTEM_PROMPT.md");

function normaliseText(value) {
	return value.split(repositoryRoot).join("<REPOSITORY_ROOT>");
}

function normaliseValue(value) {
	if (Array.isArray(value)) return value.map(normaliseValue);
	if (value && typeof value === "object") {
		return Object.fromEntries(
			Object.entries(value)
				.filter(([, nested]) => nested !== undefined && typeof nested !== "function")
				.sort(([left], [right]) => left.localeCompare(right))
				.map(([key, nested]) => [key, normaliseValue(nested)]),
		);
	}
	return typeof value === "string" ? normaliseText(value) : value;
}

function markdownCodeBlock(language, content) {
	return `\`\`\`${language}\n${content.trimEnd()}\n\`\`\``;
}

const settingsManager = SettingsManager.create(repositoryRoot, agentDir);
const resourceLoader = new DefaultResourceLoader({
	cwd: repositoryRoot,
	agentDir,
	settingsManager,
	additionalExtensionPaths: [repositoryRoot],
});
await resourceLoader.reload();

const { session, extensionsResult } = await createAgentSession({
	cwd: repositoryRoot,
	agentDir,
	settingsManager,
	resourceLoader,
	sessionManager: SessionManager.inMemory(repositoryRoot),
});

try {
	if (extensionsResult.errors.length > 0) {
		throw new Error(extensionsResult.errors.map(({ path, error }) => `${path}: ${error}`).join("\n"));
	}

	// tool-policy normally applies immediately before an agent run. Apply its
	// shared pure transformation here without performing a provider request.
	const activeToolNames = applyToolPolicyToNames(session.getActiveToolNames());
	session.setActiveToolsByName(activeToolNames);
	const systemPrompt = withResearchEngineeringGuidance(session.systemPrompt, true);
	const tools = activeToolNames.map((name) => {
		const definition = session.getToolDefinition(name);
		if (!definition) throw new Error(`active tool is missing a definition: ${name}`);
		return normaliseValue({
			name: definition.name,
			label: definition.label,
			description: definition.description,
			promptSnippet: definition.promptSnippet,
			promptGuidelines: definition.promptGuidelines,
			parameters: definition.parameters,
		});
	});

	const generated = [
		"<!-- Generated by `npm run prompt:snapshot`; do not edit by hand. -->",
		"",
		"# Pre system-prompt baseline",
		"",
		"This is the provider-independent client input assembled by Pi for the",
		"repository baseline in `pre` tmux mode. It contains the system-prompt text",
		"and active tool definitions sent by the client. It intentionally excludes",
		"dynamic project context (for example a target project's `AGENTS.md`),",
		"conversation history, credentials, provider-specific serialization, and any",
		"provider-side hidden instructions.",
		"",
		"## System prompt",
		"",
		markdownCodeBlock("text", normaliseText(systemPrompt)),
		"",
		"## Active tool definitions",
		"",
		...tools.flatMap((tool) => [
			`### \`${tool.name}\``,
			"",
			markdownCodeBlock("json", JSON.stringify(tool, null, 2)),
			"",
		]),
	].join("\n");

	mkdirSync(dirname(outputPath), { recursive: true });
	writeFileSync(outputPath, `${generated}\n`);
	console.log(`Wrote ${relative(repositoryRoot, outputPath)}`);
} finally {
	session.dispose();
}
